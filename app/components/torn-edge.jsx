function buildPath(points, viewW, viewH, side) {
  const pts = points.map(([xPct, amp]) => [
    (xPct / 100) * viewW,
    side === "top" ? amp * viewH : viewH - amp * viewH,
  ]);

  let d = `M ${pts[0][0].toFixed(2)},${pts[0][1].toFixed(2)}`;
  const n = pts.length;
  for (let i = 0; i < n - 1; i++) {
    const p0 = pts[i - 1] || pts[i];
    const p1 = pts[i];
    const p2 = pts[i + 1];
    const p3 = pts[i + 2] || p2;
    const c1x = p1[0] + (p2[0] - p0[0]) / 6;
    const c1y = p1[1] + (p2[1] - p0[1]) / 6;
    const c2x = p2[0] - (p3[0] - p1[0]) / 6;
    const c2y = p2[1] - (p3[1] - p1[1]) / 6;
    d += ` C ${c1x.toFixed(2)},${c1y.toFixed(2)} ${c2x.toFixed(2)},${c2y.toFixed(2)} ${p2[0].toFixed(2)},${p2[1].toFixed(2)}`;
  }
  const lastX = pts[n - 1][0];
  const baseline = side === "top" ? viewH : 0;
  d += ` L ${lastX.toFixed(2)},${baseline.toFixed(2)} L ${pts[0][0].toFixed(2)},${baseline.toFixed(2)} Z`;
  return d;
}

export default function TornEdge({
  side = "top",
  height = 40,
  className = "",
}) {
  const points = side === "top" ? TOP_POINTS : BOTTOM_POINTS;
  const d = useMemo(
    () => buildPath(points, 1000, height, side),
    [points, height, side],
  );

  return (
    <svg
      viewBox={`0 0 1000 ${height}`}
      preserveAspectRatio="none"
      aria-hidden="true"
      style={{
        position: "absolute",
        left: 0,
        right: 0,
        width: "100%",
        height: `${height}px`,
        display: "block",
        // [side]: `-${height}px`,
        [side]: `-${height - 2}px`,
      }}
      className={className}
    >
      <path d={d} fill="currentColor" />
    </svg>
  );
}
