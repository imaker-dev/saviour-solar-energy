// GET SERVICE BY SLUG
export function getServiceBySlug(id) {
  const service = services.find((service) => service.id === id);

  if (!service) return null;

  const { card, ...serviceDetails } = service;

  return serviceDetails;
}

// GET SERVICE CARDS
export function getServiceCards() {
  return services.map((service) => ({
    id: service.id,
    ...service.card,
  }));
}

export const generateServiceDropdownMenu = () =>
  services.map(({ id, card }) => ({
    label: card.title,
    href: `/services/${id}`,
  }));
